import {readdir,readFile,writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {join} from 'node:path';
async function list(dir){const entries=await readdir(dir,{withFileTypes:true});return(await Promise.all(entries.map(e=>e.isDirectory()?list(join(dir,e.name)):join(dir,e.name)))).flat()}
const files=(await list('dist')).filter(f=>!f.endsWith('.map')&&!f.endsWith('/sw.js')).sort();
const hash=createHash('sha256');for(const file of files)hash.update(await readFile(file));
const version=hash.digest('hex').slice(0,16);
const paths=files.map(f=>'/'+f.slice(5).replaceAll('\\','/'));
await writeFile('dist/sw.js',`// Generated by scripts/build-pwa.mjs. Public application assets only.
const CACHE = 'ebg-shell-${version}';
const ASSETS = ${JSON.stringify(paths)};
self.addEventListener('install', event => {
 event.waitUntil(caches.open(CACHE).then(cache => cache.addAll(ASSETS)));
});
self.addEventListener('activate', event => {
 event.waitUntil(caches.keys().then(keys => Promise.all(keys.filter(k => k.startsWith('ebg-shell-') && k !== CACHE).map(k => caches.delete(k)))).then(() => self.clients.claim()));
});
self.addEventListener('fetch', event => {
 const request = event.request;
 const url = new URL(request.url);
 // Never intercept authentication, inventory, reports, or any other API request.
 if (request.method !== 'GET' || url.origin !== self.location.origin || url.pathname === '/api' || url.pathname.startsWith('/api/')) return;
 if (request.mode === 'navigate') {
  event.respondWith(fetch(request).catch(() => caches.open(CACHE).then(cache => cache.match('/index.html'))));
  return;
 }
 if (ASSETS.includes(url.pathname)) {
  event.respondWith(caches.open(CACHE).then(async cache => (await cache.match(url.pathname)) || fetch(request)));
 }
});
`);
console.log(`PWA: precached ${paths.length} public files; version ${version}. No API data cached.`);
